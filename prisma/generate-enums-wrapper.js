#!/usr/bin/env node
// Auto-generate enums.mjs and enums.d.ts from the Prisma browser client
// This creates standalone ES module enums without importing the CommonJS module

const fs = require('fs');
const path = require('path');

const indexBrowserPath = path.join(__dirname, 'index-browser.js');
const indexDtsPath = path.join(__dirname, 'index.d.ts');
const enumsMjsPath = path.join(__dirname, 'enums.mjs');
const enumsDtsPath = path.join(__dirname, 'enums.d.ts');

// Read the index-browser.js file
const content = fs.readFileSync(indexBrowserPath, 'utf-8');

// Extract enum definitions with their values
// Pattern: exports.EnumName = exports.$Enums.EnumName = { key: 'value', ... };
const enumPattern = /exports\.(\w+) = exports\.\$Enums\.\1 = (\{[^}]+\});/g;
const enums = [];
let match;

while ((match = enumPattern.exec(content)) !== null) {
  const enumName = match[1];
  const enumValues = match[2];
  enums.push({ name: enumName, values: enumValues });
}

// Generate enum exports with actual values for .mjs
const enumExports = enums.map(({ name, values }) =>
  `export const ${name} = ${values};`
).join('\n\n');

// Create $Enums object for .mjs
const enumsObject = enums.map(({ name }) => `  ${name}`).join(',\n');

const mjsOutput = `// ES module wrapper for Prisma enums
// Auto-generated by generate-enums-wrapper.js - do not edit manually
// This file is regenerated every time you run 'prisma generate'

${enumExports}

export const $Enums = {
${enumsObject}
};
`;

// Generate TypeScript definitions for .d.ts
const dtsEnumExports = enums.map(({ name, values }) => {
  // Parse the values object to create TypeScript type
  const keys = values.match(/(\w+):/g).map(k => k.slice(0, -1));
  const typeUnion = keys.map(k => `'${k}'`).join(' | ');

  return `export const ${name}: {
  ${keys.map(k => `${k}: '${k}'`).join(',\n  ')}
};

export type ${name} = typeof ${name}[keyof typeof ${name}];`;
}).join('\n\n');

const dtsEnumsObject = enums.map(({ name }) => `  ${name}: typeof ${name}`).join(',\n');

const dtsOutput = `// TypeScript definitions for Prisma enums
// Auto-generated by generate-enums-wrapper.js - do not edit manually
// This file is regenerated every time you run 'prisma generate'

${dtsEnumExports}

export const $Enums: {
${dtsEnumsObject}
};
`;

fs.writeFileSync(enumsMjsPath, mjsOutput, 'utf-8');
fs.writeFileSync(enumsDtsPath, dtsOutput, 'utf-8');
console.log(`✓ Generated enums.mjs and enums.d.ts with ${enums.length} enums: ${enums.map(e => e.name).join(', ')}`);
